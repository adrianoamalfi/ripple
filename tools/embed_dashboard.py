"""PlatformIO pre-build script: embeds the dashboard into the firmware.

Reads firmware_assets/dashboard.html.gz (built by `npm run build` in web/) and
generates a header with the bytes in PROGMEM. If the asset is missing, the
header says so and the firmware falls back to the small built-in page, so the
firmware still builds for people without Node.js.
"""
import hashlib
import os

Import("env")  # noqa: F821  (provided by PlatformIO / SCons)

project = env["PROJECT_DIR"]  # noqa: F821
asset = os.path.join(project, "firmware_assets", "dashboard.html.gz")
out_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")  # noqa: F821
header = os.path.join(out_dir, "dashboard_gz.h")
os.makedirs(out_dir, exist_ok=True)

data = open(asset, "rb").read() if os.path.exists(asset) else b""
etag = hashlib.sha1(data).hexdigest()[:12] if data else "none"

rows = []
for i in range(0, len(data), 16):
    rows.append("  " + ",".join("0x%02x" % b for b in data[i : i + 16]))
body = ",\n".join(rows) if rows else "  0x00"

text = f"""// Generated by tools/embed_dashboard.py - do not edit.
#pragma once
#include <pgmspace.h>
#include <stddef.h>
#include <stdint.h>

#define RIPPLE_HAS_DASHBOARD {1 if data else 0}
#define DASHBOARD_GZ_LEN {len(data)}
#define DASHBOARD_ETAG "{etag}"

static const uint8_t DASHBOARD_GZ[] PROGMEM = {{
{body}
}};
"""

# Only touch the file when it changed, so unchanged builds stay incremental.
if not os.path.exists(header) or open(header).read() != text:
    with open(header, "w") as f:
        f.write(text)

env.Append(CPPPATH=[out_dir])  # noqa: F821
print(
    "Dashboard asset: %s"
    % (("%.1f KB gzip, etag %s" % (len(data) / 1024.0, etag)) if data else "missing (using built-in page)")
)
